#!/usr/bin/env python3
"""V5.4 LIVE order-intent risk gate. NO ORDER API/NETWORK CAPABILITY.

Inputs MUST be generated by a separate, verified broker read-only process.
This module never submits any brokerage request or approves transmission.
"""
import argparse
import datetime as dt
import hashlib
import json
import os
import re
from decimal import Decimal, InvalidOperation, ROUND_DOWN
from pathlib import Path
from zoneinfo import ZoneInfo

KST = ZoneInfo('Asia/Seoul')
CODES = re.compile(r'^[0-9]{6}$')
Q = Decimal('0.001')

class Denied(Exception):
    pass

def decimal(value):
    if isinstance(value, bool) or value is None:
        raise Denied('INVALID_NUMERIC_INPUT')
    try:
        v = Decimal(str(value))
    except (InvalidOperation, ValueError):
        raise Denied('INVALID_NUMERIC_INPUT') from None
    if not v.is_finite() or v < 0:
        raise Denied('INVALID_NUMERIC_INPUT')
    return v

def percent(value, label):
    v=decimal(value)
    if v > 100:
        raise Denied('INVALID_'+label)
    return v

def session(now):
    if now.weekday() > 4:
        return 'CLOSED'
    minutes=now.hour*60+now.minute
    if 540<=minutes<930:
        return 'REGULAR'
    if 940<=minutes<1200:
        return 'EVENING_REVIEW'
    return 'CLOSED'

def gate(data, now, reserve_pct=40, stock_pct=30, evening_pct=30):
    """Reject missing evidence; never returns a transmit authorization."""
    reserve=percent(reserve_pct,'RESERVE_PCT')
    stock=percent(stock_pct,'STOCK_PCT')
    evening=percent(evening_pct,'EVENING_PCT')
    if not isinstance(data,dict):
        raise Denied('INVALID_INPUT')
    if data.get('schema_version')!=1:
        raise Denied('INVALID_SCHEMA')
    # A false flag means not merely unknown but explicitly unverified.
    required = ('broker_cash_verified','positions_verified','unfilled_verified',
                'daily_loss_verified','quotes_fresh_verified','exchange_tradability_verified',
                'broker_history_reconciled')
    if any(data.get(k) is not True for k in required):
        raise Denied('EVIDENCE_NOT_VERIFIED')
    if data.get('as_of')!=now.strftime('%Y-%m-%d'):
        raise Denied('STALE_ACCOUNT_EVIDENCE')
    if data.get('emergency_halt') is not False:
        raise Denied('HALT_OR_UNKNOWN')
    if decimal(data.get('daily_loss_krw')) >= decimal(data.get('daily_loss_limit_krw')):
        raise Denied('DAILY_LOSS_LIMIT')
    market=session(now)
    if market=='CLOSED':
        raise Denied('MARKET_CLOSED')
    candidates=data.get('candidates')
    if not isinstance(candidates,list) or not candidates:
        raise Denied('NO_CANDIDATES')
    cash=decimal(data.get('buying_power_krw'))
    trading=(cash*(100-reserve)/100).to_integral_value(rounding=ROUND_DOWN)
    stock_cap=(trading*stock/100).to_integral_value(rounding=ROUND_DOWN)
    evening_cap=(trading*evening/100).to_integral_value(rounding=ROUND_DOWN)
    # Today's existing pending/executed BUY reservations reduce the same daily pool.
    used=decimal(data.get('today_reserved_and_filled_buy_krw'))
    if used>trading: raise Denied('EXPOSURE_EXCEEDS_BUDGET')
    remaining=trading-used
    if market=='EVENING_REVIEW':
        spent=decimal(data.get('evening_spent_and_reserved_krw'))
        if spent>evening_cap: raise Denied('EVENING_EXPOSURE_EXCEEDS_CAP')
        remaining=min(remaining,evening_cap-spent)
    seen=set()
    proposals=[]
    for row in candidates:
        if not isinstance(row,dict): raise Denied('INVALID_CANDIDATE')
        code=row.get('ticker')
        if not isinstance(code,str) or not CODES.fullmatch(code) or code in seen:
            raise Denied('INVALID_OR_DUPLICATE_CANDIDATE')
        seen.add(code)
        if row.get('broker_held') is not False or row.get('unfilled_buy') is not False:
            proposals.append({'ticker':code,'status':'BLOCKED_HELD_OR_PENDING','qty':0})
            continue
        price=decimal(row.get('indicative_limit_price_krw'))
        if price<=0:raise Denied('INVALID_PRICE')
        per_name_existing=decimal(row.get('existing_exposure_krw'))
        permitted=max(Decimal('0'),stock_cap-per_name_existing)
        cap=min(permitted,remaining,decimal(row.get('broker_symbol_buying_power_krw')))
        # Cushion for fees and quote movement, not an executable order price.
        qty=int((cap/(price*Decimal('1.002'))).to_integral_value(rounding=ROUND_DOWN))
        qty=max(0,qty)
        notional=price*qty
        remaining-=notional*Decimal('1.002')
        intent_id=hashlib.sha256((data['as_of']+'|'+market+'|'+code+'|BUY').encode()).hexdigest()[:24]
        proposals.append({'ticker':code,'status':'BLOCKED_NO_ORDER_TRANSMISSION',
                          'qty':qty,'estimate_krw':int(notional),'intent_id':intent_id})
    return {'status':'DENY_TRANSMISSION','session':market,'date':data['as_of'],
            'reserve_pct':str(reserve),'trading_pct':str(100-reserve),
            'per_stock_pct_of_trading':str(stock),'evening_pct_of_trading':str(evening),
            'trading_budget_krw':int(trading),'per_stock_cap_krw':int(stock_cap),
            'evening_budget_cap_krw':int(evening_cap),'intents':proposals,
            'broker_order_api_calls':0,'orders_sent':0,
            'LIVE_ENABLED':False,'KIS_ALLOW_ORDER':False,
            'actual_broker_trade_authorization':False}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--input',default='example_unverified.json')
    ap.add_argument('--output',default='v5_4_review.json')
    ap.add_argument('--reserve-pct',default='40')
    ap.add_argument('--stock-pct',default='30')
    ap.add_argument('--evening-pct',default='30')
    args=ap.parse_args()
    if os.getenv('LIVE_ENABLED','false').lower()!='false' or os.getenv('KIS_ALLOW_ORDER','false').lower()!='false':
        raise SystemExit('V5.4 HARD_DENY: LIVE_SWITCH_MUST_REMAIN_OFF; orders_sent=0')
    now=dt.datetime.now(KST)
    try:
        obj=json.loads(Path(args.input).read_text(encoding='utf-8'))
        result=gate(obj,now,args.reserve_pct,args.stock_pct,args.evening_pct)
    except (Denied, OSError, ValueError, TypeError) as exc:
        allowed={'EVIDENCE_NOT_VERIFIED','STALE_ACCOUNT_EVIDENCE','HALT_OR_UNKNOWN',
            'DAILY_LOSS_LIMIT','MARKET_CLOSED','NO_CANDIDATES','INVALID_SCHEMA'}
        reason=str(exc) if str(exc) in allowed else 'INVALID_OR_UNAVAILABLE_EVIDENCE'
        result={'status':'DENY','reason':reason,'orders_sent':0,'broker_order_api_calls':0,
                'LIVE_ENABLED':False,'KIS_ALLOW_ORDER':False,'actual_broker_trade_authorization':False}
    Path(args.output).write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('V5.4 GATE='+result['status']+'; reason='+result.get('reason','REVIEW_INTENTS_ONLY')+
          '; orders_sent=0; broker_order_api_calls=0; LIVE_ENABLED=false; KIS_ALLOW_ORDER=false')

if __name__=='__main__':main()
